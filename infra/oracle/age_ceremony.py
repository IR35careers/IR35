def native_windows(): return os.name == 'nt'


def sha256(body):
    return hashlib.sha256(body).hexdigest()


def physical(path):
    path = Path(path)
    if not path.is_absolute(): raise CeremonyRefused('AbsolutePhysicalPathRequired')
    for part in (path, *path.parents):
        if part.is_symlink() or getattr(part, 'is_junction', lambda: False)():
            raise CeremonyRefused('ReparsePathRefused')
    return path


def directory_custody(path):
    """Read-only check. Never change an existing directory's ACL implicitly."""
    path = physical(path)
    info = path.lstat()
    if not stat.S_ISDIR(info.st_mode): raise CeremonyRefused('ExistingProtectedDirectoryRequired')
    if not native_windows():
        if info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) != 0o700:
            raise CeremonyRefused('OwnerProtectedDirectoryRequired')
        return
    literal = str(path).replace("'", "''")
    script = ("$ErrorActionPreference='Stop';$p='" + literal + "';"
        "$s=[System.Security.Principal.WindowsIdentity]::GetCurrent().User;$a=Get-Acl -LiteralPath $p;"
        "$r=@($a.GetAccessRules($true,$true,[System.Security.Principal.SecurityIdentifier]));"
        "$owner=@($r|Where-Object {$_.IdentityReference -eq $s -and $_.AccessControlType -eq 'Allow'});"
        "$bad=@($r|Where-Object {$_.IsInherited -or $_.AccessControlType -ne 'Allow' -or "
        "($_.IdentityReference.Value -ne $s.Value -and $_.IdentityReference.Value -ne 'S-1-5-18')});"
        "if(-not $a.AreAccessRulesProtected -or $a.GetOwner([System.Security.Principal.SecurityIdentifier]) -ne $s "
        "-or $owner.Count -eq 0 -or $bad.Count -ne 0){exit 1};[Console]::Write('ok')")
    system = os.environ.get('SystemRoot', r'C:\Windows')
    reply = subprocess.run([str(Path(system) / 'System32/WindowsPowerShell/v1.0/powershell.exe'), '-NoProfile', '-NonInteractive',
        '-EncodedCommand', base64.b64encode(script.encode('utf-16le')).decode()], capture_output=True, timeout=20,
        creationflags=subprocess.CREATE_NO_WINDOW, env={'SystemRoot': system, 'WINDIR': system})
    if reply.returncode or reply.stdout != b'ok': raise CeremonyRefused('OwnerProtectedDirectoryRequired')


def custody(path, *, apply=False):
    """Protect ONLY the DACL; never use Set-Acl or request audit privileges."""
    if not native_windows(): return portable_custody(path, apply=apply)
    path = physical(path); info = path.lstat()
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1: raise CeremonyRefused('OneRegularPrivateArtifactRequired')
    if apply: _set_windows_owner_dacl(path)
    literal = str(path).replace("'", "''")
    script = ("$ErrorActionPreference='Stop';$p='" + literal + "';"
        "$s=[System.Security.Principal.WindowsIdentity]::GetCurrent().User;$a=Get-Acl -LiteralPath $p;"
        "if($a.GetOwner([System.Security.Principal.SecurityIdentifier]) -ne $s){exit 1};")
    script += ("$r=@($a.GetAccessRules($true,$true,[System.Security.Principal.SecurityIdentifier]));"
        "if(-not $a.AreAccessRulesProtected -or $r.Count -ne 1 -or $r[0].IdentityReference -ne $s "
        "-or $r[0].IsInherited -or $r[0].AccessControlType -ne 'Allow' "
        "-or $a.GetOwner([System.Security.Principal.SecurityIdentifier]) -ne $s){exit 1};[Console]::Write('ok')")
    system = os.environ.get('SystemRoot', r'C:\Windows')
    reply = subprocess.run([str(Path(system) / 'System32/WindowsPowerShell/v1.0/powershell.exe'), '-NoProfile', '-NonInteractive',
        '-EncodedCommand', base64.b64encode(script.encode('utf-16le')).decode()], capture_output=True, timeout=20,
        creationflags=subprocess.CREATE_NO_WINDOW, env={'SystemRoot': system, 'WINDIR': system})
    if reply.returncode or reply.stdout != b'ok': raise CeremonyRefused('OwnerOnlyPrivateArtifactAclRequired')


def _set_windows_owner_dacl(path, *, temporary_directory=False):
    """DACL-only Win32 repair. No owner/group/SACL modification or elevation.

    Microsoft SetNamedSecurityInfoW accepts an explicit information bitmask.
    Passing ONLY DACL_SECURITY_INFORMATION|PROTECTED_DACL_SECURITY_INFORMATION
    avoids PowerShell Set-Acl writing other descriptor sections. The directory
    option is solely for a NEW synthetic TemporaryDirectory test fixture.
    """
    path = physical(path); info = path.lstat()
    if temporary_directory:
        import tempfile
        if (not stat.S_ISDIR(info.st_mode) or any(path.iterdir())
                or not path.resolve().is_relative_to(Path(tempfile.gettempdir()).resolve())):
            raise CeremonyRefused('EmptySyntheticTemporaryDirectoryRequired')
    elif not stat.S_ISREG(info.st_mode) or info.st_nlink != 1 or info.st_size != 0:
        raise CeremonyRefused('EmptyExclusivePrivateArtifactRequired')
    if not native_windows(): raise CeremonyRefused('NativeWindowsDaclRequired')
    advapi = ctypes.WinDLL('advapi32', use_last_error=True)
    kernel = ctypes.WinDLL('kernel32', use_last_error=True)
    pointer = ctypes.c_void_p; pointer_out = ctypes.POINTER(pointer)
    dword = wintypes.DWORD; bool_out = ctypes.POINTER(wintypes.BOOL)
    kernel.GetCurrentProcess.restype = wintypes.HANDLE
    kernel.CloseHandle.argtypes = [wintypes.HANDLE]; kernel.CloseHandle.restype = wintypes.BOOL
    kernel.LocalFree.argtypes = [pointer]; kernel.LocalFree.restype = pointer
    advapi.OpenProcessToken.argtypes = [wintypes.HANDLE, dword, ctypes.POINTER(wintypes.HANDLE)]
    advapi.OpenProcessToken.restype = wintypes.BOOL
    advapi.GetTokenInformation.argtypes = [wintypes.HANDLE, ctypes.c_int, pointer, dword, ctypes.POINTER(dword)]
    advapi.GetTokenInformation.restype = wintypes.BOOL
    advapi.GetNamedSecurityInfoW.argtypes = [wintypes.LPWSTR, ctypes.c_int, dword, pointer_out,
                                           pointer_out, pointer_out, pointer_out, pointer_out]
    advapi.GetNamedSecurityInfoW.restype = dword
    advapi.EqualSid.argtypes = [pointer, pointer]; advapi.EqualSid.restype = wintypes.BOOL
    advapi.ConvertSidToStringSidW.argtypes = [pointer, pointer_out]
    advapi.ConvertSidToStringSidW.restype = wintypes.BOOL
    advapi.ConvertStringSecurityDescriptorToSecurityDescriptorW.argtypes = [wintypes.LPCWSTR, dword, pointer_out, ctypes.POINTER(dword)]
    advapi.ConvertStringSecurityDescriptorToSecurityDescriptorW.restype = wintypes.BOOL
    advapi.GetSecurityDescriptorDacl.argtypes = [pointer, bool_out, pointer_out, bool_out]
    advapi.GetSecurityDescriptorDacl.restype = wintypes.BOOL
    advapi.SetNamedSecurityInfoW.argtypes = [wintypes.LPWSTR, ctypes.c_int, dword, pointer, pointer, pointer, pointer]
    advapi.SetNamedSecurityInfoW.restype = dword
    token = wintypes.HANDLE(); source_sd = pointer(); sid_text = pointer(); new_sd = pointer()
    def check(ok):
        if not ok: raise CeremonyRefused('DaclOnlyWin32Failed_WinError_' + str(ctypes.get_last_error()))
    def status(code):
        if code: raise CeremonyRefused('DaclOnlyWin32Failed_WinError_' + str(code))
    try:
        check(advapi.OpenProcessToken(kernel.GetCurrentProcess(), 0x0008, ctypes.byref(token)))  # TOKEN_QUERY only.
        length = dword()
        advapi.GetTokenInformation(token, 1, None, 0, ctypes.byref(length))  # TokenUser, read only.
        if not 0 < length.value <= 65536: raise CeremonyRefused('CurrentOwnerSidRequired')
        buffer = ctypes.create_string_buffer(length.value)
        check(advapi.GetTokenInformation(token, 1, buffer, length, ctypes.byref(length)))
        sid = ctypes.cast(buffer, pointer_out).contents
        owner = pointer(); group = pointer()
        status(advapi.GetNamedSecurityInfoW(str(path), 1, 0x00000001 | 0x00000002,
            ctypes.byref(owner), ctypes.byref(group), None, None, ctypes.byref(source_sd)))
        check(advapi.EqualSid(owner, sid))  # Refuse ownership changes, even to the current user.
        check(advapi.ConvertSidToStringSidW(sid, ctypes.byref(sid_text)))
        inheritance = 'OICI' if temporary_directory else ''
        sddl = 'D:P(A;' + inheritance + ';FA;;;' + ctypes.wstring_at(sid_text) + ')'
        check(advapi.ConvertStringSecurityDescriptorToSecurityDescriptorW(sddl, 1, ctypes.byref(new_sd), None))
        present = wintypes.BOOL(); defaulted = wintypes.BOOL(); dacl = pointer()
        check(advapi.GetSecurityDescriptorDacl(new_sd, ctypes.byref(present), ctypes.byref(dacl), ctypes.byref(defaulted)))
        if not present.value or not dacl.value: raise CeremonyRefused('ExplicitOwnerDaclRequired')
        status(advapi.SetNamedSecurityInfoW(str(path), 1, 0x00000004 | 0x80000000, None, None, dacl, None))
        after_sd = pointer(); after_owner = pointer(); after_group = pointer()
        try:
            status(advapi.GetNamedSecurityInfoW(str(path), 1, 0x00000001 | 0x00000002,
                ctypes.byref(after_owner), ctypes.byref(after_group), None, None, ctypes.byref(after_sd)))
            check(advapi.EqualSid(owner, after_owner)); check(advapi.EqualSid(group, after_group))
        finally:
            if after_sd: kernel.LocalFree(after_sd)
    finally:
        for allocation in (source_sd, sid_text, new_sd):
            if allocation: kernel.LocalFree(allocation)
        if token: kernel.CloseHandle(token)


def verify_tools(age_path, keygen_path, age_sha, keygen_sha, version):
    result = {}
    if not re.fullmatch(r'v[0-9]+\.[0-9]+\.[0-9]+', version or ''):
        raise CeremonyRefused('ExactReviewedAgeVersionRequired')
    for name, value, pin in (('age.exe', age_path, age_sha), ('age-keygen.exe', keygen_path, keygen_sha)):
        path = physical(value)
        info = path.lstat()
        if (path.name != name or not stat.S_ISREG(info.st_mode) or info.st_nlink != 1
                or not re.fullmatch('[a-f0-9]{64}', pin or '') or sha256(path.read_bytes()) != pin):
            raise CeremonyRefused('ReviewedOfficialExecutableHashRequired')
        result[name] = path
    if result['age.exe'].parent != result['age-keygen.exe'].parent:
        raise CeremonyRefused('SameReviewedAgeReleaseDirectoryRequired')
    return result


def owned_descriptor(path, fd):
    current, held = path.lstat(), os.fstat(fd)
    if (path.is_symlink() or not stat.S_ISREG(current.st_mode) or current.st_nlink != 1 or held.st_nlink != 1
            or (current.st_dev, current.st_ino) != (held.st_dev, held.st_ino)):
        raise CeremonyRefused('ExclusiveArtifactIdentityChanged')


def open_private(path):
    fd = os.open(path, os.O_RDWR | os.O_CREAT | os.O_EXCL | getattr(os, 'O_NOFOLLOW', 0) | getattr(os, 'O_BINARY', 0), 0o600)
    try:
        custody(path, apply=True)  # Empty until owner-only DACL/mode is verified.
        owned_descriptor(path, fd)
        return fd
    except BaseException:
        os.close(fd)
        raise  # Preserve this empty reservation, never recreate on retry.


def fill_descriptor(path, fd, body):
    if type(body) is not bytes or not body or len(body) > 65536:
        raise CeremonyRefused('BoundedExplicitArtifactBytesRequired')
    owned_descriptor(path, fd); custody(path)
    if os.fstat(fd).st_size != 0: raise CeremonyRefused('EmptyReservedArtifactRequired')
    with os.fdopen(fd, 'r+b', closefd=False) as stream:
        stream.write(body); stream.flush(); os.fsync(fd)
        stream.seek(0)
        if stream.read(len(body) + 1) != body: raise CeremonyRefused('ArtifactReadbackMismatch')
    owned_descriptor(path, fd); custody(path)


def write_private(path, body):
    fd = open_private(path)
    try: fill_descriptor(path, fd, body)
    finally: os.close(fd)


def age_call(args, *, body=None):
    # No inherited provider/credential/plugin/debug environment, interactive
    # console, command shell, raw child output/exception or automatic retry.
    system = os.environ.get('SystemRoot', r'C:\Windows')
    try:
        reply = subprocess.run([str(arg) for arg in args], input=body, capture_output=True, timeout=30,
            creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0), env={'SystemRoot': system, 'WINDIR': system})
    except Exception:
        raise CeremonyRefused('OfficialAgeCommandFailed_RawWithheld') from None
    if reply.returncode or len(reply.stdout) > 65536 or len(reply.stderr) > 65536:
        raise CeremonyRefused('OfficialAgeCommandFailed_RawWithheld')
    return reply.stdout


def perform_ceremony(directory, tools, version):
    """Root executes once after publisher/hash review; tests inject fake age_call.

    The CLI locks the actual owner-authorised destination. This core accepts a
    temporary owner700 directory solely for synthetic offline unit fixtures.
    """
    directory = physical(directory); directory_custody(directory)
    if set(tools) != {'age.exe', 'age-keygen.exe'}: raise CeremonyRefused('BothReviewedAgeExecutablesRequired')
    paths = {name: directory / name for name in NAMES}
    if any(path.exists() or path.is_symlink() for path in paths.values()):
        raise CeremonyRefused('ExistingCeremonyArtifactPreserved_NoRetry')
    for name in ('age.exe', 'age-keygen.exe'):
        if age_call([tools[name], '--version']).strip() != version.encode():
            raise CeremonyRefused('ExactReviewedAgeVersionRequired')
    identity_path = paths[IDENTITY_NAME]
    fd = open_private(identity_path)  # Exclusive reservation BEFORE keygen.
    started = False
    result = {'status': 'FAIL', 'identity_file': str(identity_path), 'private_identity_printed': False,
              'private_identity_copied_to_vm_or_bucket': False, 'vm_calls': 0, 'cloud_calls': 0,
              'owner_action': 'store an offline copy of the age key file in your password manager or on a USB drive'}
    try:
        write_private(paths[INTENT_NAME], (json.dumps(result | {'operation': 'one-local-age-key-generation', 'version': version}, sort_keys=True) + '\n').encode())
        started = True
        identity = age_call([tools['age-keygen.exe']])
        lines = identity.splitlines()
        private = [line for line in lines if line and not line.startswith(b'#')]
        if len(identity) > 4096 or len(private) != 1 or not re.fullmatch(rb'AGE-SECRET-KEY-1[0-9A-Z]{58}', private[0]):
            raise CeremonyRefused('OneTraditionalNativeAgeIdentityRequired')
        recipient = age_call([tools['age-keygen.exe'], '-y'], body=identity).strip()
        if not PUBLIC_PATTERN.fullmatch(recipient): raise CeremonyRefused('OneNativeAgePublicRecipientRequired')
        fill_descriptor(identity_path, fd, identity)
        identity = None; private = None; lines = None
        write_private(paths[RECIPIENT_NAME], recipient + b'\n')
        write_private(paths[SYNTHETIC_NAME], SYNTHETIC)
        ciphertext = age_call([tools['age.exe'], '--encrypt', '--recipient', recipient.decode()], body=SYNTHETIC)
        if not ciphertext.startswith(b'age-encryption.org/v1\n') or ciphertext == SYNTHETIC:
            raise CeremonyRefused('AgeCiphertextFramingRequired')
        write_private(paths[CIPHERTEXT_NAME], ciphertext)
        owned_descriptor(identity_path, fd); custody(identity_path)
        restored = age_call([tools['age.exe'], '--decrypt', '--identity', identity_path], body=ciphertext)
        if restored != SYNTHETIC: raise CeremonyRefused('SyntheticAgeRoundTripMismatch')
        write_private(paths[RESTORED_NAME], restored)
        result.update(status='PASS', version=version, recipient=recipient.decode(), recipient_sha256=sha256(recipient),
            identity_owner_only=True, identity_bytes=os.fstat(fd).st_size, key_generation_calls=1,
            synthetic_bytes=len(SYNTHETIC), synthetic_sha256=sha256(SYNTHETIC), ciphertext_sha256=sha256(ciphertext),
            synthetic_encrypt_decrypt='PASS')
    except Exception as error:
        # The only strings included are controlled codes, never a subprocess
        # message, key, token, plaintext, stderr, argv, locals or traceback.
        result['code'] = str(error) if type(error) is CeremonyRefused else type(error).__name__
        result['key_generation_may_have_run'] = started
    finally:
        os.close(fd)
    write_private(paths[RECEIPT_NAME], (json.dumps(result, sort_keys=True, indent=2) + '\n').encode())
    if result['status'] != 'PASS': raise CeremonyRefused('CeremonyFailed_PrivateReceiptPreserved_NoRetry')
    return result


def main(argv=None):
    parser = SafeParser(description='One native local age ceremony; public paths/pins only.')
    parser.add_argument('--age-path', required=True); parser.add_argument('--keygen-path', required=True)
    parser.add_argument('--age-sha256', required=True); parser.add_argument('--keygen-sha256', required=True)
    parser.add_argument('--version', required=True)
    try:
        args = parser.parse_args(argv)
        if not native_windows(): raise CeremonyRefused('NativeWindowsCeremonyRequired')
        tools = verify_tools(args.age_path, args.keygen_path, args.age_sha256, args.keygen_sha256, args.version)
        result = perform_ceremony(DIRECTORY, tools, args.version)
        print(json.dumps(result, sort_keys=True)); return 0
    except BaseException:
        # Fixed summary only. A reserved identity/receipt is NEVER overwritten
        # or silently replaced; reconcile locally before requesting any retry.
        print(json.dumps({'status': 'STOP', 'code': 'LocalAgeCeremonyStopped_NoRetry_RawWithheld',
                          'identity_file': str(DIRECTORY / IDENTITY_NAME)})); return 1


